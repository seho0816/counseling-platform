package com.counseling.backend.counseling;

import com.counseling.backend.security.ActiveActorService;
import com.counseling.backend.user.User;
import com.counseling.backend.user.UserRole;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.http.HttpStatus;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.security.core.Authentication;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.web.server.ResponseStatusException;
import tools.jackson.databind.json.JsonMapper;

@Service
public class CounselingSummaryService {
    private final CounselingSessionRepository sessions;
    private final CounselingSummaryRepository summaries;
    private final ActiveActorService actors;
    private final SummaryGenerator generator;
    private final JsonMapper mapper;

    public CounselingSummaryService(CounselingSessionRepository sessions,
                                    CounselingSummaryRepository summaries,
                                    ActiveActorService actors,
                                    SummaryGenerator generator,
                                    JsonMapper mapper) {
        this.sessions = sessions;
        this.summaries = summaries;
        this.actors = actors;
        this.generator = generator;
        this.mapper = mapper;
    }

    @Transactional(readOnly = true)
    @PreAuthorize("hasAnyRole('ADMIN', 'COUNSELOR')")
    public SummaryResponse get(Long sessionId, Authentication authentication) {
        User actor = actors.requireAny(authentication, UserRole.ADMIN, UserRole.COUNSELOR);
        authorizedSession(sessionId, actor);
        CounselingSummary summary = summaries.findBySession_Id(sessionId)
            .orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND, "Summary not found"));
        return response(summary);
    }

    @Transactional
    @PreAuthorize("hasAnyRole('ADMIN', 'COUNSELOR')")
    public SummaryResponse generate(Long sessionId, Authentication authentication) {
        User actor = actors.requireAny(authentication, UserRole.ADMIN, UserRole.COUNSELOR);
        CounselingSession session = authorizedSession(sessionId, actor);
        if (summaries.existsBySession_Id(sessionId)) {
            throw new ResponseStatusException(HttpStatus.CONFLICT, "A draft already exists for this session");
        }

        // The real AI integration is supplied by a separate SummaryGenerator bean.
        // Never substitute a canned or hardcoded draft and claim it was generated by AI.
        GeneratedSummary generated = generator.generate(session.getContent());
        if (generated == null || generated.draft() == null
                || generated.modelName() == null || generated.modelName().isBlank()
                || generated.modelName().length() > 100) {
            throw new ResponseStatusException(HttpStatus.BAD_GATEWAY, "Invalid AI response");
        }

        SummaryFields draft;
        try {
            draft = generated.draft().validated();
        } catch (IllegalArgumentException ex) {
            throw new ResponseStatusException(HttpStatus.BAD_GATEWAY, "Invalid AI summary fields", ex);
        }
        CounselingSummary summary = new CounselingSummary(
            session, mapper.writeValueAsString(draft), generated.modelName().strip());
        try {
            // The database UNIQUE(session_id) is the final duplicate-generation guard.
            return response(summaries.saveAndFlush(summary));
        } catch (DataIntegrityViolationException ex) {
            throw new ResponseStatusException(HttpStatus.CONFLICT,
                "A summary already exists for this session", ex);
        }
    }

    @Transactional
    @PreAuthorize("hasRole('COUNSELOR')")
    public SummaryResponse confirm(Long sessionId, ConfirmSummaryRequest request,
                                   Authentication authentication) {
        User reviewer = actors.require(authentication, UserRole.COUNSELOR);
        authorizedSession(sessionId, reviewer);
        if (request == null || request.finalSummary() == null) {
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "finalSummary is required");
        }
        SummaryFields reviewed;
        try {
            reviewed = request.finalSummary().validated();
        } catch (IllegalArgumentException ex) {
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "Invalid final summary", ex);
        }

        CounselingSummary summary = summaries.findBySession_Id(sessionId)
            .orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND, "Summary not found"));
        if (summary.getStatus() == SummaryStatus.CONFIRMED) {
            throw new ResponseStatusException(HttpStatus.CONFLICT, "Summary already confirmed");
        }
        summary.confirm(reviewer, mapper.writeValueAsString(reviewed));
        return response(summaries.saveAndFlush(summary));
    }

    private CounselingSession authorizedSession(Long sessionId, User actor) {
        if (sessionId == null || sessionId < 1) {
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "Invalid session ID");
        }
        CounselingSession session = sessions.findById(sessionId)
            .orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND, "Session not found"));
        if (actor.getRole() == UserRole.COUNSELOR) {
            User assigned = session.getCounselingCase().getCounselor();
            if (assigned == null || !actor.getId().equals(assigned.getId())) {
                // Do not reveal the existence of another counselor's session.
                throw new ResponseStatusException(HttpStatus.NOT_FOUND, "Session not found");
            }
        }
        return session;
    }

    private SummaryResponse response(CounselingSummary summary) {
        try {
            return SummaryResponse.from(summary, mapper);
        } catch (RuntimeException ex) {
            throw new ResponseStatusException(HttpStatus.INTERNAL_SERVER_ERROR,
                "Stored summary has an invalid format", ex);
        }
    }
}
